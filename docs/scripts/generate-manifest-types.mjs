import { readFileSync, writeFileSync } from 'node:fs'

const [metadataPath = 'docs/public/generated/manifest-metadata.json', outputPath = 'crates/pgroles-wasm/policy-authoring.d.ts'] = process.argv.slice(2)
const metadata = JSON.parse(readFileSync(metadataPath, 'utf8'))

function definitionName(reference) {
  return reference.split('/').at(-1).replaceAll(/[^A-Za-z0-9_]/g, '_')
}

function schemaType(schema, root, stack = new Set()) {
  if (!schema || typeof schema !== 'object') return 'unknown'
  const { allOf, anyOf, oneOf, ...siblings } = schema
  if (Array.isArray(allOf)) {
    const siblingType = Object.keys(siblings).length > 0
      ? schemaType(siblings, root, stack)
      : null
    return [siblingType, ...allOf.map((variant) => schemaType(variant, root, stack))]
      .filter((type) => type && type !== 'unknown')
      .join(' & ') || 'unknown'
  }
  if (Array.isArray(anyOf) || Array.isArray(oneOf)) {
    const siblingType = Object.keys(siblings).length > 0
      ? schemaType(siblings, root, stack)
      : null
    const variants = [...(anyOf ?? []), ...(oneOf ?? [])]
      .map((variant) => schemaType(variant, root, stack))
      .filter(Boolean)
    const union = variants.join(' | ') || 'unknown'
    return siblingType && siblingType !== 'unknown'
      ? `${siblingType} & (${union})`
      : union
  }
  if (schema.$ref) {
    const name = definitionName(schema.$ref)
    return name
  }
  if (Object.hasOwn(schema, 'const')) return JSON.stringify(schema.const)
  if (Array.isArray(schema.enum)) {
    return schema.enum.map((value) => JSON.stringify(value)).join(' | ')
  }
  if (Array.isArray(schema.type)) {
    return schema.type
      .map((type) => schemaType({ ...schema, type }, root, stack))
      .join(' | ')
  }
  if (schema.type === 'array') {
    return `Array<${schemaType(schema.items, root, stack)}>`
  }
  if (schema.type === 'object' || schema.properties || schema.additionalProperties) {
    const required = new Set(schema.required ?? [])
    const properties = Object.entries(schema.properties ?? {}).map(
      ([name, property]) =>
        `${JSON.stringify(name)}${required.has(name) ? '' : '?'}: ${schemaType(property, root, stack)}`
    )
    const additional = schema.additionalProperties
      ? ` & Record<string, ${
          schema.additionalProperties === true
            ? 'unknown'
            : schemaType(schema.additionalProperties, root, stack)
        }>`
      : ''
    return `{ ${properties.join('; ')} }${additional}`
  }
  if (schema.type === 'string') return 'string'
  if (schema.type === 'integer' || schema.type === 'number') return 'number'
  if (schema.type === 'boolean') return 'boolean'
  if (schema.type === 'null') return 'null'
  return 'unknown'
}

function schemaDeclarations(root, preferredName) {
  const definitions = root.$defs ?? root.definitions ?? {}
  const namedDefinitions = Object.entries(definitions)
    .map(([name, schema]) => `export type ${definitionName(name)} = ${schemaType(schema, root)}\n`)
    .join('')
  return `${namedDefinitions}export type ${preferredName} = ${schemaType(root, root)}\n`
}

const contracts = metadata.contracts ?? {}
const contractDeclarations = Object.entries(contracts)
  .map(
    ([name, schema]) =>
      `export namespace ${name}Schema {\n${schemaDeclarations(schema, 'Value')}\n}\nexport type ${name} = ${name}Schema.Value\n`
  )
  .join('\n')

const engineDeclaration = contracts.PolicyRequest && contracts.ValidateResponse && contracts.CompileResponse
  ? `export interface PolicyAuthoringEngine {\n  validate(input: PolicyRequest): ValidateResponse\n  compile(input: PolicyRequest): CompileResponse\n}\n`
  : ''

const output = `// Generated by docs/scripts/generate-manifest-types.mjs. Do not edit.\n\nexport type ManifestMetadataSchemaVersion = ${JSON.stringify(metadata.schema_version)}\n\n${schemaDeclarations(metadata.manifest_schema, 'PolicyManifest')}\n${contractDeclarations}\n${engineDeclaration}`

writeFileSync(outputPath, output)
