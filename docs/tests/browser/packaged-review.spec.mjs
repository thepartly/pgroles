import { expect, test } from '@playwright/test'
import { readFile } from 'node:fs/promises'

const artifactPath = process.env.PGROLES_REVIEW_ARTIFACT

test('imports a review generated by the packaged release candidate', async ({ page }) => {
  test.skip(!artifactPath, 'Run scripts/check-packaged-review.sh with the candidate archive')
  const artifact = JSON.parse(await readFile(artifactPath, 'utf8'))
  expect(process.env.PGROLES_CANDIDATE_VERSION).toBe(`pgroles ${artifact.provenance.tool_version}`)
  expect(artifact.recorded.changes.some((entry) => entry.change.kind === 'create_role')).toBeTruthy()
  const wasmRequests = []
  page.on('request', (request) => {
    if (request.url().includes('/wasm/')) wasmRequests.push(request.url())
  })
  await page.goto('docs/explorer/')
  await page.getByLabel('Recorded review file').setInputFiles(artifactPath)
  const review = page.getByRole('region', { name: 'Recorded plan review' })
  await expect(review).toBeVisible()
  await expect(review.getByRole('heading', { name: 'Packaged candidate review' })).toBeVisible()
  await expect(review.getByText('Create role', { exact: true }).first()).toBeVisible()
  await expect(review.getByText(/CREATE ROLE "review_app" LOGIN/)).toBeVisible()
  await expect(review.getByText(/Hypothetical variation unavailable/i)).toBeVisible()
  expect(wasmRequests).toEqual([])
})
