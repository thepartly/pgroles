test('reader disclosure choices persist while automatic expansion follows the page', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('docs/quick-start/')
  const navigation = page.getByRole('navigation', { name: 'Docs navigation', exact: true })
  await navigation.getByRole('button', { name: 'Reference', exact: true }).click()
  await navigation.getByRole('button', { name: 'Kubernetes operator', exact: true }).click()
  await navigation.getByRole('link', { name: 'Troubleshooting', exact: true }).click()
  await expect(navigation.getByRole('button', { name: 'Get started', exact: true })).toHaveAttribute('aria-expanded', 'false')
  await expect(navigation.getByRole('button', { name: 'Reference', exact: true })).toHaveAttribute('aria-expanded', 'true')
  await page.reload()
  await expect(navigation.getByRole('button', { name: 'Reference', exact: true })).toHaveAttribute('aria-expanded', 'true')
  await page.setViewportSize({ width: 390, height: 820 })
  await page.getByRole('button', { name: 'Open navigation', exact: true }).click()
  const mobileReference = page.getByRole('dialog').getByRole('button', { name: 'Reference', exact: true })
  await expect(mobileReference).toHaveAttribute('aria-expanded', 'true')
  await mobileReference.click()
  await expect(mobileReference).toHaveAttribute('aria-expanded', 'false')
  await page.keyboard.press('Escape')
  await page.setViewportSize({ width: 1440, height: 900 })
  await expect(navigation.getByRole('button', { name: 'Reference', exact: true })).toHaveAttribute('aria-expanded', 'false')
})

for (const width of [360, 390, 768]) {
  test(`mobile destinations and direct RLS discovery at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 820 })
    await page.goto('docs/operator-install/')
    await page.getByRole('button', { name: 'Open navigation', exact: true }).click()
    let sheet = page.getByRole('dialog')
    await expect(sheet.getByRole('heading', { name: 'Docs', exact: true })).toBeVisible()
    const docsNavigation = sheet.getByRole('navigation', { name: 'Docs navigation', exact: true })
    await docsNavigation.getByRole('button', { name: 'Get started', exact: true }).click()
    await docsNavigation.getByRole('link', { name: 'Operator quick start', exact: true }).click()
    await expect(sheet).toBeHidden()
    await expect(page).toHaveURL(/\/docs\/operator-quick-start\/$/)

    await page.getByRole('button', { name: 'Open navigation', exact: true }).click()
    await sheet.getByRole('link', { name: 'Learn PostgreSQL', exact: true }).click()
    await expect(sheet).toBeHidden()
    await expect(page.getByRole('heading', { name: 'Learn PostgreSQL roles', exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'Open navigation', exact: true }).click()
    await expect(sheet.getByRole('heading', { name: 'Learn PostgreSQL', exact: true })).toBeVisible()
    const learnNavigation = sheet.getByRole('navigation', { name: 'Learn PostgreSQL navigation', exact: true })
    const advanced = learnNavigation.getByRole('button', { name: 'Advanced', exact: true })
    if (await advanced.count() && await advanced.getAttribute('aria-expanded') === 'false') await advanced.click()
    await learnNavigation.getByRole('link', { name: '8. Row-level security', exact: true }).click()
    await expect(sheet).toBeHidden()
    await expect(page.getByRole('heading', { name: '8. Same table, different rows', exact: true })).toBeVisible()
    await page.reload()
    await page.getByRole('button', { name: 'Open navigation', exact: true }).click()
    await expect(learnNavigation.getByRole('link', { name: '8. Row-level security', exact: true })).toHaveAttribute('aria-current', 'page')
    await expect(learnNavigation.getByRole('link', { name: /operator|Plan explorer/i })).toHaveCount(0)
    await sheet.getByRole('link', { name: 'Explorer', exact: true }).click()
    await expect(sheet).toBeHidden()
    await page.getByLabel('Recorded review file').setInputFiles(reviewFixture)
    await expect(page.getByRole('region', { name: 'Recorded plan review' })).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth)).toBeLessThanOrEqual(1)
  })
}
