test('operator troubleshooting opens directly with its active entry in view', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 700 })
  await page.addInitScript(() => {
    for (const section of ['Get started', 'Write policy', 'Connect and adopt', 'Plan and review']) {
      sessionStorage.setItem(`pgroles.navigation.docs.${section}`, 'true')
    }
  })
  await page.goto('docs/operator-troubleshooting/#a-plan-does-not-execute')
  const navigation = page.getByRole('navigation', { name: 'Docs navigation', exact: true })
  const active = navigation.getByRole('link', { name: 'Troubleshooting', exact: true })
  await expect(navigation.getByRole('button', { name: 'Kubernetes operator', exact: true })).toHaveAttribute('aria-expanded', 'true')
  await expect(active).toHaveAttribute('aria-current', 'page')
  await expect(active).toBeInViewport()
  await expect(page.locator('article').getByRole('heading', { name: 'A plan does not execute', exact: true })).toBeInViewport()
  await expect(navigation.getByText('Operations', { exact: true })).toBeVisible()
})

