import { expect, test } from '@playwright/test'
import { resolve } from 'node:path'

const reviewFixture = resolve(import.meta.dirname, '../fixtures/recorded-review.json')

test('product navigation reaches the operator quick start once and gives a deliberate next step', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('')
  const navigation = page.getByRole('navigation', { name: 'Docs navigation', exact: true })
  const quickStart = navigation.getByRole('link', { name: 'Operator quick start', exact: true })
  await expect(quickStart).toHaveCount(1)
  await expect(navigation.getByRole('link', { name: /permission chain/ })).toHaveCount(0)
  await expect(navigation.getByRole('button', { name: 'Kubernetes operator', exact: true })).toHaveAttribute('aria-expanded', 'false')
  await quickStart.click()
  await expect(page).toHaveURL(/\/docs\/operator-quick-start\/$/)
  await expect(quickStart).toHaveAttribute('aria-current', 'page')
  await expect(page.locator('dl').filter({ hasText: 'Next' }).getByRole('link')).toHaveAttribute('href', /\/docs\/operator\/$/)
  await expect(page.getByRole('navigation', { name: 'Breadcrumb' })).toContainText('Get started')
})

