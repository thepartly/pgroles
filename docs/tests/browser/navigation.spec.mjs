test('320px header, sheet and field discovery work from the keyboard without page overflow', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 820 })
  await page.goto('docs/manifest-reference/')
  const noOverflow = async () => expect(await page.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth)).toBeLessThanOrEqual(1)
  await noOverflow()
  const menu = page.getByRole('button', { name: 'Open navigation', exact: true })
  await page.keyboard.press('Tab')
  await expect(menu).toBeFocused()
  await page.keyboard.press('Enter')
  const sheet = page.getByRole('dialog')
  await expect(sheet).toBeVisible()
  expect(await sheet.evaluate((element) => element.scrollWidth - element.clientWidth)).toBeLessThanOrEqual(1)
  const reference = sheet.getByRole('button', { name: 'Reference', exact: true })
  await reference.focus()
  await page.keyboard.press('Space')
  await expect(reference).toHaveAttribute('aria-expanded', 'false')
  await page.keyboard.press('Space')
  await expect(reference).toHaveAttribute('aria-expanded', 'true')
  await page.keyboard.press('Escape')
  await expect(menu).toBeFocused()
  const theme = page.getByRole('button', { name: 'Theme', exact: true })
  await theme.focus()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('menu')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(theme).toBeFocused()
  const contents = page.locator('summary').filter({ hasText: 'On this page' })
  await contents.focus()
  await page.keyboard.press('Enter')
  const membership = page.getByRole('navigation', { name: 'On this page' }).getByRole('link', { name: 'memberships', exact: true })
  await membership.focus()
  await page.keyboard.press('Enter')
  await expect(page).toHaveURL(/#memberships$/)
  const field = page.locator('article tr').filter({ has: page.getByText('exclusive', { exact: true }) })
  await expect(field).toContainText('external: true')
  await noOverflow()
  const tableRegion = page.getByRole('region', { name: 'Table', exact: true }).filter({ has: page.getByText('exclusive', { exact: true }) })
  await tableRegion.focus()
  await expect(tableRegion).toBeFocused()
  const canScroll = await tableRegion.evaluate((element) => element.scrollWidth > element.clientWidth)
  if (canScroll) {
    await page.keyboard.press('ArrowRight')
    await expect.poll(() => tableRegion.evaluate((element) => element.scrollLeft)).toBeGreaterThan(0)
  }
  await page.goto('docs/reference/postgrespolicyplan-v1alpha1/')
  await noOverflow()
  await page.goto('docs/cli/')
  await noOverflow()
})

